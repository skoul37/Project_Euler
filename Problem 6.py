
# Project Euler - Problem 6: Sum square difference
# Βρες τη διαφορά μεταξύ του αθροίσματος των τετραγώνων των πρώτων 100 φυσικών αριθμών και του τετραγώνου του αθροίσματος.

# Αρχικοποίηση μεταβλητών για το άθροισμα των τετραγώνων (suma1) και το άθροισμα των αριθμών (suma2)
suma1, suma2 = 0, 0

# Υπολογισμός του αθροίσματος των τετραγώνων για τους αριθμούς από το 1 έως το 100
for i in range(1, 101):
    suma1 = suma1 + i**2

# Υπολογισμός του απλού αθροίσματος για τους αριθμούς από το 1 έως το 100
for i in range(1, 101):
    suma2 = suma2 + i

# Υπολογισμός και εκτύπωση της διαφοράς: (τετράγωνο του αθροίσματος) - (άθροισμα των τετραγώνων)
print(suma2**2 - suma1)