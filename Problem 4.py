# Δημιουργία κενής λίστας για τα γινόμενα που είναι παλινδρομικοί αριθμοί
t = []

# Εξωτερικός βρόχος για τριψήφιους αριθμούς k (από 100 έως 999)
for k in range(100, 1000):
    # Εσωτερικός βρόχος από το k έως το 999 (ξεκινάει από το k για να αποφεύγει διπλούς ελέγχους)
    for i in range(k, 1000):
        # Έλεγχος αν το γινόμενο μετατραπεί σε string διαβάζεται το ίδιο ανάποδα (είναι παλίνδρομο)
        if str(k * i) == str(k * i)[::-1]:
            # Προσθήκη του παλινδρομικού γινομένου στη λίστα
            t = t + [k * i]

# Ταξινόμηση της λίστας σε αύξουσα σειρά
t.sort()

# Εκτύπωση του μεγαλύτερου στοιχείου (του τελευταίου της ταξινομημένης λίστας)
print(t[-1])

    

