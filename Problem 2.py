# Αρχικοποίηση της λίστας με τους τρεις πρώτους αριθμούς της ακολουθίας
s = [1, 2, 3]

# Αρχικοποίηση της προσωρινής μεταβλητής x
x = 0

# Επανάληψη όσο ο τελευταίος αριθμός της λίστας είναι μικρότερος από 4.000.000
while s[-1] < 4000000:
    # Υπολογισμός του επόμενου αριθμού ως το άθροισμα των δύο τελευταίων
    x = s[-1] + s[-2]
    # Προσθήκη του νέου αριθμού στο τέλος της λίστας
    s.append(x)
    # Επαναφορά της μεταβλητής x στο 0
    x = 0

# Υπολογισμός και εκτύπωση του αθροίσματος όλων των ζυγών (even) αριθμών στη λίστα
print(sum(i for i in s if i % 2 == 0))   



    
