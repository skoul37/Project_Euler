import time

# Project Euler - Problem 46: Goldbach's other conjecture
# Εύρεση του μικρότερου περιττού σύνθετου αριθμού που ΔΕΝ ικανοποιεί την εικασία 
# του Goldbach (δηλ. δεν γράφεται ως άθροισμα πρώτου + 2 * τετράγωνο).

# Συνάρτηση που παράγει τους πρώτους αριθμούς και τους περιττούς σύνθετους μέχρι το n
def isprime (n):
    for x in range(7, n, 2):
        isprime = True
        # Έλεγχος αν ο αριθμός x είναι σύνθετος
        for y in range(3, int(x**0.5) + 1, 2):
            if x % y == 0:
                odd.append(x)    # Αν διαιρείται, προστίθεται στη λίστα των περιττών σύνθετων αριθμών
                isprime = False
                break
        # Αν δεν βρέθηκε διαιρέτης, είναι πρώτος
        if isprime:
            pr.append(x)         # Προστίθεται στη λίστα των πρώτων αριθμών

# Καταγραφή χρόνου εκτέλεσης
t = time.time()

s = []
pr = [3, 5]               # Αρχική λίστα με τους πρώτους 3 και 5
odd = []                  # Λίστα για τους περιττούς σύνθετους αριθμούς
sq = [2 * i**2 for i in range(1, 100)]  # Λίστα με τα διπλάσια των τετραγώνων (2 * 1^2, 2 * 2^2, κ.λπ.)

# Κλήση της συνάρτησης για έλεγχο έως το 10000
isprime(10000)

# Έλεγχος για κάθε περιττό σύνθετο αριθμό (a) αν μπορεί να γραφτεί ως (πρώτος b + διπλό τετράγωνο)
for a in odd:
    for b in pr:
        if a - b > 0 and a - b in sq:
            s.append(a)   # Αν επαληθεύεται η εικασία, αποθηκεύεται στη λίστα s
            break

# Εντοπισμός και εκτύπωση του αριθμού που δεν επαληθεύει την εικασία (δεν βρίσκεται στη λίστα s)
for r in odd:
    if r not in s:
        print(r)

# Εκτύπωση συνολικού χρόνου εκτέλεσης του προγράμματος
print(time.time() - t)
