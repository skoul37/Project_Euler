def protos (p):
    """
    Αυτή η συνάρτηση ελέγχει αν ένας περιττός αριθμός p είναι πρώτος. 
    Ξεκινάει υποθέτοντας ότι είναι πρώτος (isprime=True) και τον δοκιμάζει διαιρώντας τον 
    με περιττούς αριθμούς από το 3 μέχρι την τετραγωνική του ρίζα (int(p**0.5) + 1). 
    Αν βρεθεί ακριβής διαιρέτης, ο αριθμός δεν είναι πρώτος, οπότε διακόπτεται ο βρόχος (break). 
    Αν επιβεβαιωθεί ότι είναι πρώτος, προστίθεται απευθείας στη global λίστα s.
    """
    isprime = True
    for i in range(3, int(p**0.5) + 1, 2):
        if p % i == 0:
            isprime = False
            break
    if isprime:
        s.append(p)

# Αρχικοποιούμε τη λίστα s με τους τέσσερις πρώτους μικρούς πρώτους αριθμούς.
s = [2, 3, 5, 7]
print(len(s))

counter = 0

# Σάρωση για εύρεση πρώτων:
# Ο παρακάτω βρόχος διατρέχει όλους τους περιττούς αριθμούς από το 11 έως τα 50.000.000 
# και καλεί τη συνάρτηση protos για να χτίσει τη μεγάλη λίστα με τους πρώτους αριθμούς.
for p in range(11, 50000000, 2):
    protos(p)

print(len(s))

# Υπολογισμός συνδυασμών γινομένων πρώτων:
# Με δύο εμφωλευμένους βρόχους, εξετάζουμε όλα τα δυνατά ζεύγη πρώτων αριθμών (s[x], s[y]) 
# από τη λίστα μας. Αν το γινόμενό τους ξεπεράσει ή ισúσει με το 10^8 (100.000.000), 
# διακόπτεται ο εσωτερικός βρόχος (break) χάρη στην ταξινόμηση της λίστας. 
# Αλλιώς, αυξάνουμε τον μετρητή (counter) κατά 1 για κάθε έγκυρο ζεύγος που ικανοποιεί το όριο.
for x in range(0, len(s)):
    for y in range(x, len(s)):
        if s[x] * s[y] >= 10**8:
            break
        else:
            counter = counter + 1

# Εκτυπώνουμε το συνολικό πλήθος των ζευγών που πληρούν τη συνθήκη
print(counter)
