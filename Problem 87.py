s2 = [2, 3, 5, 7]
s3 = []
s4 = []
l = []
r = []

# Δημιουργία λίστας πρώτων αριθμών: 
# Ο παρακάτω βρόχος ελέγχει τους περιττούς αριθμούς από το 11 έως το 7071 (καθώς 7071^2 ≈ 50.000.000) 
# και προσθέτει όσους είναι πρώτοι στη λίστα s2.
for i in range(11, 7071, 2):
    isprime = True 
    for y in range(3, int(i**0.5) + 1, 2):
        if i % y == 0:
            isprime = False
            break
    if isprime:
        s2.append(i)

# Δημιουργία υπο-λίστας για κύβους (s3): 
# Επιλέγουμε από τους πρώτους εκείνους των οποίων ο κύβος δεν ξεπερνά τα 50.000.000.
for i in s2:
    if i**3 < 50000000:
        s3.append(i)

# Δημιουργία υπο-λίστας για τέταρτες δυνάμεις (s4): 
# Επιλέγουμε τους πρώτους των οποίων η τέταρτη δύναμη δεν ξεπερνά τα 50.000.000.
for i in s2:
    if i**4 < 50000000:
        s4.append(i)

# Υπολογισμός όλων των πιθανών συνδυασμών:
# Με τρεις εμφωλευμένους βρόχους, δοκιμάζουμε όλες τις τριάδες πρώτων αριθμών (a, b, c) 
# από τις αντίστοιχες λίστες, σχηματίζοντας τον αριθμό x = a^2 + b^3 + c^4. 
# Αν είναι μικρότερος από 50.000.000, τον αποθηκεύουμε στη λίστα l.
for a in s2:
    for b in s3:
        for c in s4:
            x = a**2 + b**3 + c**4
            if x < 50000000:
                l.append(x)

# Ταξινόμηση της λίστας l ώστε οι ίδιοι αριθμοί να βρεθούν διπλανοί.
l.sort()

# Εντοπισμός διπλότυπων αθροισμάτων:
# Αν ένας αριθμός μπορεί να προκύψει με περισσότερους από έναν συνδυασμούς πρώτων,
# θα εμφανιστεί διαδοχικά στη ταξινομημένη λίστα, οπότε τον καταγράφουμε στη λίστα r.
for a in range(1, len(l)):
    if l[a] == l[a - 1]:
        r.append(l[a])

# Εκτυπώνουμε το τελικό πλήθος των μοναδικών αριθμών 
# (αφαιρώντας τα διπλότυπα από το συνολικό πλήθος).
print(len(l) - len(r))
        
   
    








