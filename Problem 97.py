# Ξεκινάμε με μια αρχική δύναμη του 2 (το 2^30 = 1.073.741.824), 
# η οποία διευκολύνει την εκκίνηση του πολλαπλασιασμού.
x = 1073741824

# Ο παρακάτω βρόχος επαναλαμβάνεται από το 31 μέχρι το 7.830.457, 
# υπολογίζοντας διαδοχικά τις δυνάμεις του 2 (2^n).
for i in range(31, 7830458):
    x = x * 2
    
    # Τεχνασμός περικοπής ψηφίων (Modulo / String Slicing): 
    # Επειδή μας ενδιαφέρουν αποκλειστικά και μόνο τα τελευταία 10 ψηφία του αριθμού, 
    # απομονώνουμε το trailing κομμάτι με τη μετατροπή σε string [-10:] 
    # και το επαναφέρουμε σε ακέραιο. Αυτό εμποδίζει την υπερχείλιση μνήμης 
    # και κρατάει τους υπολογισμούς εξαιρετικά γρήγορους, καθώς δεν κουβαλάμε 
    # εκατομμύρια άχρηστα ψηφία.
    y = str(x)[-10:]
    x = int(y)

# Αφού υπολογίσουμε τα τελευταία 10 ψηφία του 2^7830457, 
# πολλαπλασιάζουμε επί το σταθερό 28433 και προσθέτουμε τη μονάδα (+1), 
# όπως ορίζει ο τύπος του προβλήματος.
x = x * 28433 + 1

# Εκτυπώνουμε τα τελευταία 10 ψηφία του τελικού αποτελέσματος.
print(str(x)[-10:])
   
