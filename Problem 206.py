# Κεντρικός βρόχος αναζήτησης:
# Σαρώνει έναν τεράστιο αριθμητικό χώρο από το 1.010.101.010 έως το 1.389.026.623, 
# κάνοντας βήματα των 10 μονάδων (range με βήμα 10) για εξοικονόμηση χρόνου.
for i in range(1010101010, 1389026623, 10):
    
    # Υπολογίζουμε το τετράγωνο του τρέχοντος αριθμού i και το μετατρέπουμε σε string, 
    # ώστε να μπορέσουμε να επεξεργαστούμε απευθείας τα ψηφία του ως συμβολοσειρά.
    x = str(i**2)
    
    # Έλεγχος μοτίβου (String Slicing με βήμα):
    # Εξετάζουμε τα ψηφία του τετραγώνου με βήμα 2 (δηλαδή x[0:19:2]), 
    # απομονώνοντας συγκεκριμένες θέσεις χαρακτήρων για να εντοπίσουμε 
    # αν ταιριάζουν ακριβώς με το ζητούμενο μοτίβο '1234567890'.
    if (x[0:19:2]) == '1234567890':
        # Αν βρεθεί ο αριθμός που ικανοποιεί τη συνθήκη, τον τυπώνουμε στην οθόνη 
        # και τερματίζουμε αμέσως την εκτέλεση του προγράμματος (exit).
        print(i)
        exit()
    

