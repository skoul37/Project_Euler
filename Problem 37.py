# Project Euler - Problem 37: Truncatable primes
# Υπολογισμός του αθροίσματος των 11 πρώτων αριθμών που είναι "κομμένοι" (truncatable) 
# τόσο από τα αριστερά όσο και από τα δεξιά, παραμένοντας πάντα πρώτοι.

s = []  # Λίστα για την αποθήκευση των υποψήφιων πρώτων αριθμών
l = []  # Βοηθητική λίστα για την αποθήκευση όσων απορρίπτονται

# Βήμα 1: Εύρεση όλων των περιττών πρώτων αριθμών από το 11 μέχρι το 1.000.000
for i in range(11, 1000001, 2):
    isprime = True
    # Έλεγχος διαιρετότητας μέχρι την τετραγωνική ρίζα του i
    for x in range(3, int(i**0.5) + 1, 2):
        if i % x == 0:
            isprime = False
            break
    if isprime:
        s.append(i)

# Βήμα 2: Αρχικός αποκλεισμός πρώτων που περιέχουν το ψηφίο 1 στην αρχή ή στο τέλος
# (καθώς οι κομμένοι αριθμοί με 1 δεν μπορούν να δώσουν σταθερά πρώτους)
for i in s[:]:
    if int(str(i)[0]) == 1 or int(str(i)[-1]) == 1:
        s.remove(i)

# Βήμα 3: Έλεγχος κοψίματος από ΑΡΙΣΤΕΡΑ προς τα δεξιά (Left-to-right truncation)
for i in s[:]:
    y = str(i)
    n = 1
    while n < len(y):
        # Αφαίρεση ψηφίων από τα αριστερά (π.χ. από '3797' σε '797', μετά '97', '7')
        x = int(y[0:len(y) - n])
        isPrime = True
        # Έλεγχος αν ο νέος αριθμός είναι πρώτος
        for r in range(2, int(x**0.5) + 1):
            if x % r == 0:
                isPrime = False
                l.append(i)  # Αν δεν είναι πρώτος, προσθέτουμε τον αριθμό στη λίστα απόρριψης l
                n = n + len(y)  # Τερματισμός ελέγχου για τον τρέχοντα αριθμό
                break
        if isPrime:
            n = n + 1

# Αφαίρεση των μη-έγκυρων αριθμών που απέτυχαν στον αριστερό έλεγχο
for i in l[:]:
    s.remove(i)

# Επαναφορά της βοηθητικής λίστας l για τον επόμενο έλεγχο
l = []

# Βήμα 4: Έλεγχος κοψίματος από ΔΕΞΙΑ προς τα αριστερά (Right-to-left truncation)
for i in s[:]:
    y = str(i)
    n = 1
    while n < len(y):
        # Αφαίρεση ψηφίων από τα δεξιά (π.χ. από '3797' σε '379', μετά '37', '3')
        x = int(y[-(len(y) - n):])
        isPrimes = True
        # Έλεγχος αν ο νέος αριθμός είναι πρώτος
        for r in range(2, int(x**0.5) + 1):
            if x % r == 0:
                isPrimes = False
                l.append(i)  # Αν δεν είναι πρώτος, τον προσθέτουμε στη λίστα απόρριψης
                n = len(y)   # Τερματισμός ελέγχου
                break
        if isPrimes:
            n = n + 1

# Αφαίρεση όσων απέτυχαν και στον δεξιό έλεγχο
for i in l[:]:
    s.remove(i)

# Βήμα 5: Υπολογισμός του αθροίσματος όλων των τελικών εγκύρων truncatable primes
suma = 0
for i in s:
    suma = suma + int(i)

# Εκτύπωση του τελικού αθροίσματος
print(suma)


        
        

            
        
        
    
    
