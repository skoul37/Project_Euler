# Project Euler - Problem 44: Pentagon numbers
# Εύρεση του ζεύγους πενταγωνικών αριθμών των οποίων το άθροισμα και η διαφορά 
# είναι επίσης πενταγωνικοί αριθμοί, ελαχιστοποιώντας τη διαφορά τους.

# Δημιουργία λίστας s με τους πρώτους 2999 πενταγωνικούς αριθμούς (P_n = n(3n-1)/2)
s = [n * (3 * n - 1) / 2 for n in range(1, 3000)]

# Σάρωση των στοιχείων της λίστας για την εξεύρεση κατάλληλου ζεύγους (pk, pj)
for pk in range(1, len(s)):
    for pj in range(pk + 1, len(s)):
        # Έλεγχος αν τόσο το άθροισμα όσο και η απόλυτη διαφορά των δύο πενταγωνικών αριθμών 
        # περιέχονται στη λίστα των πενταγωνικών αριθμών s
        if s[pk] + s[pj] in s and abs(s[pk] - s[pj]) in s:
            # Εκτύπωση της διαφοράς όταν εντοπιστεί το ζεύγος
            print(abs(s[pk] - s[pj]))
           
           
               
                
    
    


    

    


        
