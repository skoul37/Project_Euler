# Project Euler - Problem 10: Summation of primes
# Βρες το άθροισμα όλων των πρώτων αριθμών που είναι μικρότεροι από 2.000.000.

# Αρχικοποίηση λίστας s και μεταβλητής αθροίσματος c (ξεκινάμε από το 2, το οποίο προσθέτουμε εκ των προτέρων)
s = []
c = 2

# Επανάληψη για όλους τους περιττούς αριθμούς x από το 3 έως το 2.000.000 (με βήμα 2)
for x in range(3, 2000000, 2):
    isPrime = True
    # Έλεγχος διαιρετότητας με περιττούς αριθμούς από το 3 μέχρι την τετραγωνική ρίζα του x
    for y in range(3, int(x**0.5) + 1, 2):
        if x % y == 0:
            isPrime = False
            break  # Διακοπή μόλις βρεθεί διαιρέτης
            
    # Αν ο αριθμός είναι πρώτος, τον προσθέτουμε στη λίστα s
    if isPrime:
        s.append(x)

# Άθροισμα όλων των στοιχείων της λίστας s προσθέτοντάς τα στην αρχική τιμή του c
for n in s:
    c = c + int(n)

# Εκτύπωση του τελικού αθροίσματος των πρώτων αριθμών
print(c)
