from math import *

# Project Euler - Problem 39: Integer right triangles
# Εύρεση της τιμής της περιμέτρου p (p <= 1000) για την οποία ο αριθμός των 
# ορθογωνίων τριγώνων με ακέραιες πλευρές (a, b, c) είναι μέγιστος.

# Συνάρτηση που υπολογίζει πόσα ορθογώνια τρίγωνα με ακέραιες πλευρές 
# έχουν δεδομένη περίμετρο n.
def right_triangles (n):
    counter = 0
    # Η υποτείνουσα c πρέπει να είναι μικρότερη από το μισό της περιμέτρου
    for c in range(1, int(n / 2) + 1):
        # Η πλευρά a κυμαίνεται από 1 έως c-1
        for a in range(1, c):
            # Υπολογισμός της κάθετης πλευράς b από το πυθαγόρειο θεώρημα: b = sqrt(c^2 - a^2)
            b = sqrt(c**2 - a**2)
            # Αν το άθροισμα των πλευρών ισούται με την περίμετρο n
            if a + b + c == n:
                counter = counter + 1
    return counter

# Αρχικοποίηση μεταβλητών για την παρακολούθηση του μέγιστου πλήθους και της αντίστοιχης περιμέτρου
new_counter = 0
new_p = 0

# Σάρωση όλων των πιθανών τιμών της περιμέτρου n από 120 έως 1000
for n in range(120, 1001):
    # Αν ο αριθμός των λύσεων για το τρέχον n είναι μεγαλύτερος ή ίσος του τρέχοντος μέγιστου
    if new_counter <= right_triangles(n):
        new_counter = right_triangles(n)
        new_p = n
    else:
        # Διατήρηση των προηγούμενων τιμών αν δεν ξεπεραστεί το μέγιστο
        new_counter = new_counter
        new_p = new_p

# Εκτύπωση του μέγιστου πλήθους λύσεων και της αντίστοιχης περιμέτρου p
print(new_counter, new_p)





