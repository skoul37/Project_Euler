  # Project Euler - Problem 58: Spiral primes


# Συνάρτηση παραγωγής επόμενου όρου στην 1η διαγώνιο
def diagonal1 ():
     s1.append(s1[-1] + len(s1) * 8 + 2)

# Συνάρτηση παραγωγής επόμενου όρου στη 2η διαγώνιο
def diagonal2 ():
     s2.append(s2[-1] + len(s2) * 8 + 4)

# Συνάρτηση παραγωγής επόμενου όρου στην 3η διαγώνιο
def diagonal3 ():
     s3.append(s3[-1] + len(s3) * 8 + 6)

# Συνάρτηση ελέγχου αν ένας αριθμός είναι πρώτος (επιστρέφει 1 αν είναι πρώτος, 0 αν είναι σύνθετος)
def protos(n):
    isprime = True
    for i in range(3, int(n**0.5) + 1, 2):
        if n % i == 0:
            isprime = False
            return 0
    if isprime:
        return 1

counter = 3       # Πλήθος πρώτων αριθμών στις διαγώνιους (ξεκινάμε με τους 3, 5, 7 από το κέντρο)
s1 = [3]          # Λίστα για την 1η διαγώνιο
s2 = [5]          # Λίστα για τη 2η διαγώνιο
s3 = [7]          # Λίστα για την 3η διαγώνιο
length = 3        # Αρχικό μήκος πλευράς σπείρας (3x3)

# Επανάληψη όσο το ποσοστό (πλήθος πρώτων / συνολικό πλήθος αριθμών στις διαγώνιους) είναι > 10%
# Σημείωση: Το συνολικό πλήθος δίνεται από τον τύπο (1 + 4 * len(s1))
while (counter / (1 + 4 * len(s1))) > 0.1:
    length = length + 2
    diagonal1()
    diagonal2()
    diagonal3()   
    
    # Προσθήκη στο counter αν οι νέοι αριθμοί των διαγωνίων είναι πρώτοι
    counter = counter + protos(s1[-1])
    counter = counter + protos(s2[-1])
    counter = counter + protos(s3[-1])
else:
    # Όταν το ποσοστό πέσει κάτω από 10%, εκτυπώνεται το μήκος πλευράς και τερματίζεται το πρόγραμμα
    print(length)
    exit()
    


        
    
    






