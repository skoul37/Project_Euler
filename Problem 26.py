# Project Euler - Problem 26: Reciprocal cycles
# Βρες την τιμή του d < 1000 για την οποία το 1/d περιέχει τη μεγαλύτερη επαναλαμβανόμενη ακολουθία ψηφίων (recurring cycle) στο δεκαδικό του άνοιγμα.

# Συνάρτηση που βρίσκει το μήκος της περιοδικής ακολουθίας των δεκαδικών ψηφίων του κλάσματος 1/n
def reciprocal (n):
    l = [1]
    # Οι αριθμοί που διαιρούνται με το 2 ή το 5 έχουν πεπερασμένα δεκαδικά ψηφία (άρα περίοδο 1)
    if n % 2 == 0 or n % 5 == 0:
        return l
    # Προσομοίωση της διαίρεσης με το χέρι για την εύρεση των υπόλοιπων (remainders)
    while (l[-1] * 10) % n != 1 and (l[-1] * 10) % n != l[-1]:
        l.append((l[-1] * 10) % n)
        if (l[-1] * 10) % n == l[1]:
            return l
    else:
        return l

s = []
x = 0

# Έλεγχος για όλους τους παρονομαστές d από το 2 έως το 1000
for i in range(2, 1001):
    l = reciprocal(i)
    # Κρατάμε τον αριθμό που παράγει τη μακrύτερη περίοδο
    if len(s) < len(l):
        s = l
        x = i

# Εκτύπωση του αριθμού x και του μήκους της περιοδικής περιόδου του
print(x, len(s))
   




