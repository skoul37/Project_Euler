
# Project Euler - Problem 9: Special Pythagorean triplet
# Βρες το γινόμενο abc για το μοναδικό πυθαγόρειο τρίγωνο (a < b < c) όπου a + b + c = 1000.

# Εξωτερικός βρόχος για το c (υποτείνουσα) από 1 έως 999
for c in range(1, 1000):
    # Εσωτερικός βρόχος για το b από 1 έως το c-1
    for b in range(1, c):
        # Τρίτος βρόχος για το a από 1 έως το b-1
        for a in range(1, b):
            # Έλεγχος αν σχηματίζουν πυθαγόρειο τρίγωνο και το άθροισμά τους είναι 1000
            if a**2 + b**2 == c**2 and a + b + c == 1000:
                # Εκτύπωση του γινομένου των τριών αριθμών
                print(a * b * c)
                # Τερματισμός του προγράμματος μόλις βρεθεί η λύση
                exit()