from fractions import Fraction

# Project Euler - Problem 33: Digit cancelling fractions
# Βρες όλες τις μη-τετριμμένες κλασματικές περιπτώσεις (μικρότερες από 1, με διψήφιους αριθμούς)
# όπου η «αφελή» διαγραφή του κοινού ψηφίου στον αριθμητή και στον παρονομαστή 
# δίνει το ίδιο ακριβώς κλάσμα, και υπολόγισε το γινόμενό τους σε ανάγλυφη μορφή.

# Αρχικοποίηση λίστας s για την αποθήκευση των αριθμητών και παρονομαστών που ικανοποιούν τις προϋποθέσεις
s = []

# Εξωτερικός βρόχος για τον αριθμητή i (διψήφιοι αριθμοί από 10 έως 98)
for i in range(10, 99):
    # Εσωτερικός βρόχος για τον παρονομαστή j (από i+1 έως 99, ώστε να εξασφαλίσουμε i < j, δηλαδή κλάσμα < 1)
    for j in range(i+1, 100):
        # Έλεγχος συνθηκών:
        # 1. Ο παρονομαστής δεν τελειώνει σε 0 (int(str(j)[-1]) != 0) για να απορρίψουμε τετριμμένες περιπτώσεις.
        # 2. Το τελευταίο ψηφίο του αριθμητή i ισούται με το πρώτο ψηφίο του παρονομαστή j (int(str(i)[-1]) == int(str(j)[0])).
        # 3. Το πραγματικό κλάσμα (i/j) ισούται με το απλοποιημένο κλάσμα που προκύπτει από τη διαγραφή του κοινού ψηφίου.
        if int(str(j)[-1]) != 0 and int(str(i)[-1]) == int(str(j)[0]) and Fraction(i, j) == Fraction(int(str(i)[0]), int(str(j)[-1])):
            # Αν ισχύουν, προσθέτουμε τον αριθμητή i και τον παρονομαστή j στη λίστα
            s.append(i)
            s.append(j)

# Υπολογισμός και εκτύπωση του τελικού αποτελέσματος:
# Πολλαπλασιάζουμε τους παρονομαστές (θέσεις 1, 3, 5, 7) δια του γινομένου των αριθμητών (θέσεις 0, 2, 4, 6)
# ώστε να βρούμε τον παρονομαστή του τελικού γινομένου σε χαμηλότερους όρους.
print((s[1] * s[3] * s[5] * s[7]) / (s[0] * s[2] * s[4] * s[6]))


