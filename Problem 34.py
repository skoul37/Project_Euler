# Project Euler - Problem 34: Digit factorials
# Βρες το άθροισμα όλων των αριθμών που ισούνται με το άθροισμα των παραγοντικών των ψηφίων τους.

# Συνάρτηση για τον αναδρομικό υπολογισμό του παραγοντικού (factorial) ενός αριθμού n
def paragontiko(n):
    # Ο 0! (παραγοντικό του 0) εξ ορισμού ισούται με 1
    if n == 0:
        return 1
    else:
        # Αναδρομική κλήση: n! = n * (n-1)!
        return n * paragontiko(n - 1)

# Αρχικοποίηση μεταβλητής αθροίσματος παραγοντικών ψηφίων και λίστας για τα αποτελέσματα
suma = 0
s = []

# Σάρωση των αριθμών από το 3 μέχρι το 100.000 (το λογικό άνω όριο για το συγκεκριμένο πρόβλημα)
for i in range(3, 100000):
    x = str(i)
    
    # Υπολογισμός του αθροίσματος των παραγοντικών για κάθε ψηφίο ξεχωριστά
    for r in x:
        suma = suma + paragontiko(int(r))
        
    # Έλεγχος αν το άθροισμα των παραγοντικών ισούται με τον αρχικό αριθμό i
    if suma == i:
        s.append(i)
        suma = 0  # Μηδενισμός του αθροίσματος για τον επόμενο κύκλο
    else:
        suma = 0  # Μηδενισμός αν δεν ταιριάζει, προκειμένου να ελεγχθεί ο επόμενος αριθμός

# Εκτύπωση του αθροίσματος όλων των έγκυρων αριθμών που αποθηκεύτηκαν στη λίστα s
print(sum(int(i) for i in s))
    
    
    
