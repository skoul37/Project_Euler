# Project Euler - Problem 34: Digit factorials
# Βρες το άθροισμα όλων των αριθμών που ισούνται με το άθροισμα των παραγοντικών των ψηφίων τους.

# Συνάρτηση για τον αναδρομικό υπολογισμό του παραγοντικού (factorial) ενός αριθμού n
def paragontiko(n):
    # Ο 0! (παραγοντικό του 0) εξ ορισμού ισούται με 1
    if n == 0:
        return 1
    else:
        # Αναδρομική κλήση: n! = n * (n-1)!
        return n * paragontiko(n - 1)

# Αρχικοποίηση μεταβλητής αθροίσματος ψηφίων και λίστας αποθήκευσης των έγκυρων αριθμών
suma = 0
s = []

# Έλεγχος όλων των αριθμών από το 3 μέχρι το 100.000 (το άνω όριο για το πρόβλημα αυτό)
for i in range(3, 100000):
    x = str(i)
    
    # Υπολογισμός του αθροίσματος των παραγοντικών για κάθε ψηφίο του τρέχοντος αριθμού i
    for r in x:
        suma = suma + paragontiko(int(r))
        
    # Αν το άθροισμα των παραγοντικών των ψηφίων ισούται με τον ίδιο τον αριθμό i
    if suma == i:
        s.append(i)
        # Μηδενισμός του αθροίσματος για τον επόμενο αριθμό
        suma = 0
    else:
        # Μηδενισμός του αθροίσματος αν δεν ταιριάζει, ώστε να ξεκινήσουμε φρέσκοι στον επόμενο αριθμό
        suma = 0

# Εκτύπωση του αθροίσματος όλων των αριθμών που βρέθηκαν στη λίστα s
print(sum(int(i) for i in s))
    
    
