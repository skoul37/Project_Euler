# Project Euler - Problem 32: Pandigital products
# Βρες το άθροισμα όλων των αριθμών που μπορούν να γραφτούν ως γινόμενο 
# (multiplicand * multiplier = product) τέτοιο ώστε ο συνδυασμός τους να είναι 
# 1-to-9 pandigital (να περιέχει ακριβώς τα ψηφία 1 έως 9 από μία φορά το καθένα).

# Συνάρτηση που ελέγχει αν ένας αριθμός περιέχει ακριβώς τα ψηφία 1 έως 9 (pandigital 1-9)
def pandigital (n):
    # Μετατροπή του αριθμού σε string και στη συνέχεια σε λίστα χαρακτήρων (ψηφίων)
    x = list(str(n))
    # Ταξινόμηση των ψηφίων σε αύξουσα σειρά
    x.sort()
    # Το πρότυπο string που θέλουμε να αντιστοιχεί (όλα τα ψηφία από το 1 έως το 9)
    a = '123456789'
    b = ''
    # Ένωση των ταξινομημένων ψηφίων πίσω σε string
    pandigital = b.join(x)
    # Αν το string ισούται με το '123456789', τότε είναι pandigital και επιστρέφουμε 1
    if pandigital == a:
        return 1

# Αρχικοποίηση λίστας για την αποθήκευση των έγκυρων γινομένων (products)
s = []

# Περίπτωση 1: 2ψήφιος αριθμός επί 3ψήφιο αριθμό (π.χ. xx * xxx = xxxx)
# Το γινόμενο σε αυτή την περίπτωση θα είναι 4ψήφιο, οπότε συνολικά τα ψηφία θα είναι 2 + 3 + 4 = 9.
for i in range(10, 100):
    for n in range(100, 1000):
        # Ελέγχουμε αν το γινόμενο έχει ακριβώς 4 ψηφία
        if len(str(i * n)) == 4:
            # Ενώνουμε τους αριθμούς σε έναν ενιαίο αριθμό (π.χ. i + n + γινόμενο) και ελέγχουμε αν είναι pandigital
            if pandigital(int(str(i) + str(n) + str(i * n))) == 1:
                s.append(i * n)

# Περίπτωση 2: 1ψήφιος αριθμός επί 4ψήφιο αριθμό (π.χ. x * xxxx = xxxx)
# Συνολικά τα ψηφία θα είναι πάλι 1 + 4 + 4 = 9.
for i in range(1, 10):
    for n in range(1000, 9999):
        # Ελέγχουμε αν το γινόμενο έχει ακριβώς 4 ψηφία
        if len(str(i * n)) == 4:
            # Ενώνουμε τους αριθμούς και ελέγχουμε αν είναι pandigital
            if pandigital(int(str(i) + str(n) + str(i * n))) == 1:
                s.append(i * n)

# Αρχικοποίηση μεταβλητής για το τελικό άθροισμα
suma = 0

# Ταξινόμηση της λίστας των γινομένων
s.sort()
l = s

# Αφαίρεση τυχόν διπλότυπων γινομένων από τη λίστα
for i in s:
    if l.count(i) > 1:
        s.remove(i)

# Υπολογισμός του αθροίσματος όλων των μοναδικών έγκυρων γινομένων
for i in s:
    suma = suma + i

# Εκτύπωση του τελικού αθροίσματος
print(suma)

    
