l = []
s = []

def digit_sum (n):
    """
    Αυτή η συνάρτηση παίρνει έναν αριθμό n, υπολογίζει το άθροισμα των ψηφίων του 
    και στη συνέχεια ελέγχει αν αυτό το άθροισμα, υψωμένο σε κάποια δύναμη r 
    (από 2 έως 8), ισούται ακριβώς με τον αρχικό αριθμό n. 
    Αν ισχύει, ο αριθμός προστίθεται στη λίστα l των εγκurων αποτελεσμάτων.
    """
    suma = 0
    x = str(n)
    for i in x:
        suma = suma + int(i)
    for r in range(2, 9):
        if suma**r == n:
            l.append(n)
    return l

# Δημιουργία υποψήφιων δυνάμεων:
# Ο παρακάτω βρόχος παράγει μαζικά μεγάλες δυνάμεις (από τετράγωνα n^2 έως όγδοες δυνάμεις n^8) 
# για μια μεγάλη γκάμα ακεραίων από το 7 έως το 3.000, αποθηκεύοντάς τες στη λίστα s.
for n in range(7, 3000):
    s.append(n**2)
    s.append(n**3)
    s.append(n**4)
    s.append(n**5)
    s.append(n**6)
    s.append(n**7)
    s.append(n**8)

# Σάρωση και έλεγχος:
# Διατρέχουμε κάθε προϋπολογισμένη δύναμη από τη λίστα s και καλούμε 
# τη συνάρτηση digit_sum για να εντοπίσουμε ποιες ικανοποιούν την ιδιότητα.
for n in s:
    digit_sum(n)

# Ταξινομούμε τη λίστα με τα αποτελέσματα ώστε να εμφανιστούν σε αύξουσα σειρά
l.sort()

# Εκτυπώνουμε την τελική ταξινομημένη λίστα των αριθμών που πληρούν τις προϋποθέσεις
print(l)
    



    
        
