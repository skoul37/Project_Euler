import time

# Project Euler - Problem 38: Pandigital multiples
# Εύρεση του μεγαλύτερου πανψηφιακού αριθμού 1-9 που προκύπτει από 
# τη συνένωση (concatenation) των γινομένων ενός αριθμού i με ακέραιους από το 1 έως το n (όπου n > 1).

# Συνάρτηση που ελέγχει αν ένας αριθμός περιέχει ακριβώς τα ψηφία 1 έως 9 (pandigital 1-9)
def pandigital (n):
    # Μετατροπή του αριθμού σε λίστα χαρακτήρων (ψηφίων) και ταξινόμησή τους
    x = list(str(n))
    x.sort()
    a = '123456789'
    b = ''
    pandigital = b.join(x)
    
    # Αν η ενωμένη λίστα ισούται με το '123456789', επιστρέφουμε τον αριθμό n, αλλιώς 0
    if pandigital == a:
        return n
    else:
        return 0

# Καταγραφή του χρόνου έναρξης για τη μέτρηση της απόδοσης
t = time.time()
s = []

# Δοκιμή τιμών για τον αριθμό i στην περιοχή 9000 έως 9999 
# (καθώς ένας 4ψήφιος αριθμός που ξεκινά από 9 πολλαπλασιαζόμενος με 1 και 2 δίνει ακριβώς 9 ψηφία συνολικά: 4 + 5 = 9)
for i in range(9000, 9999):
     y = ''
     # Πολλαπλασιασμός του i διαδοχικά με το 1 και το 2 (n από 1 έως 2)
     for n in range(1, 3):
         x = str(i * n)
         y = y + x  # Συνένωση των γινομένων σε ένα ενιαίο string y
     # Έλεγχος αν το αποτέλεσμα είναι πανψηφιακό και αποθήκευση στη λίστα s
     s.append(pandigital(int(y)))

# Ταξινόμηση της λίστας σε αύξουσα σειρά
s.sort()

# Εκτύπωση του μεγαλύτερου στοιχείου (του τελευταίου στοιχείου της ταξινομημένης λίστας)
print(s[-1])

# Εκτύπωση του χρόνου εκτέλεσης του προγράμματος
print(time.time() - t)
         
     
        
     
     

     
     
     
         
    
         
        
