## Αρχικοποίηση κενής λίστας s
s = []

# Επανάληψη για τιμές του i από το 2 έως το 100.000.000
for i in range(2, 100000001):
    # Έλεγχος αν ο αριθμός 600851475143 διαιρείται ακριβώς με το i
    if 600851475143 % i == 0:
        # Αν διαιρείται, αποθήκευση του πηλίκου στη λίστα s
        s.append(600851475143 / i)

# Αρχικοποίηση δεύτερης κενής λίστας t
t = []

# Μετατροπή των στοιχείων της λίστας s σε ακέραιους αριθμούς
for n in s:
    x = int(n)
    t.append(x)

# Εκτύπωση της λίστας t με τους ακεραίους
print(t)

# Έλεγχος για κάθε αριθμό k στη λίστα t αν είναι πρώτος αριθμός
for k in t:
    isprime = True
    # Έλεγχος διαιρετότητας με περιττούς αριθμούς από το 3 μέχρι την τετραγωνική ρίζα του k
    for y in range(3, int(k**0.5) + 1, 2):
        if k % y == 0:
            isprime = False
            break  # Διακοπή της επανάληψης αν βρεθεί διαιρέτης

    # Αν ο αριθμός είναι πρώτος, εκτυπώνεται
    if isprime:
        print(k)
    
        

    
