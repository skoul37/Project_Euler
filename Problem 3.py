# Δημιουργία μιας κενής λίστας 's' για να αποθηκεύσουμε τους διαιρέτες
# (ή τα πηλίκα της διαίρεσης) του μεγάλου αριθμού 600851475143.
s = []

# Δημιουργία ενός βρόχου (loop) για να ελέγξουμε όλους τους αριθμούς 'i'
# από το 2 έως και το 100.000.000.
for i in range(2, 100000001):
    # Ελέγχουμε αν ο μεγάλος αριθμός 600851475143 διαιρείται ακριβώς με το 'i'
    # (δηλαδή αν το υπόλοιπο της διαίρεσης % είναι 0).
    if 600851475143 % i == 0:
        # Αν είναι ακριβής διαιρέτης, υπολογίζουμε το πηλίκο (600851475143 / i)
        # και το προσθέτουμε στη λίστα 's'.
        s.append(600851475143 / i)

# Δημιουργία μιας νέας κενής λίστας 't'
t = []

# Επαναλαμβάνουμε για κάθε στοιχείο 'n' που αποθηκεύσαμε στη λίστα 's'.
for n in s:
    # Επειδή η διαίρεση στη Python επιστρέφει αριθμό κινητής υποδιαίρεσης (float),
    # τον μετατρέπουμε σε ακέραιο (integer) αριθμό.
    x = int(n)
    # Και τον προσθέτουμε στη νέα λίστα 't'.
    t.append(x)

# Εκτυπώνουμε ολόκληρη τη λίστα 't' με τους ακέραιους αριθμούς που βρήκαμε.
print(t)

# --- ΕΛΕΓΧΟΣ ΓΙΑ ΠΡΩΤΟΥΣ ΑΡΙΘΜΟΥΣ ---
# Παίρνουμε έναν-έναν τους αριθμούς 'k' από τη λίστα 't' για να ελέγξουμε
# αν πρόκειται για πρώτους αριθμούς (prime numbers).
for k in t:
    # Υποθέτουμε αρχικά ότι ο αριθμός 'k' ΕΙΝΑΙ πρώτος (isprime = True).
    isprime = True
    
    # Εδώ γίνεται το loop για τον έλεγχο διαιρετότητας:
    # - Ξεκινάμε από το 3 (range starts at 3).
    # - Φτάνουμε μέχρι την τετραγωνική ρίζα του αριθμού (int(k**0.5) + 1).
    #   (Σημείωση: Δεν χρειάζεται να ελέγξουμε παραπέρα, γιατί αν ένας αριθμός
    #   έχει διαιρέτη μεγαλύτερο της ρίζας του, θα είχε αναγκαστικά και έναν
    #   αντίστοιχο μικρότερο διαιρέτη που θα το είχαμε ήδη βρει).
    # - Το βήμα είναι 2 (range(..., 2)), πράγμα που σημαίνει ότι ελέγχουμε
    #   ΜΟΝΟ τους περιττούς αριθμούς (3, 5, 7, 9...), αγνοώντας τους ζυγούς
    #   αφού ξέρουμε ότι ο 'k' δεν είναι άρτιος.
    for y in range(3, int(k**0.5) + 1, 2):
        # Ελέγχουμε αν ο 'k' διαιρείται ακριβώς με κάποιον από αυτούς τους αριθμούς 'y'.
        if k % y == 0:
            # Αν βρεθεί έστω και ένας διαιρέτης, τότε ο αριθμός ΔΕΝ είναι πρώτος.
            isprime = False
            # Σταματάμε αμέσως το loop (break), γιατί δεν χρειάζεται να ψάξουμε
            # παραπάνω· έχουμε ήδη αποδείξει ότι δεν είναι πρώτος.
            break

    # Αφού τελειώσει ο εσωτερικός έλεγχος:
    # Αν η σημαία (flag) 'isprime' παρέμεινε True (δηλαδή δεν βρέθηκε κανένας διαιρέτης),
    # τότε ο αριθμός είναι όντως πρώτος και τον εκτυπώνουμε.
    if isprime:
        print(k)