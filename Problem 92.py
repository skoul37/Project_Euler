s = []
t = []

# Σαρώνουμε όλους τους αριθμούς από το 1 έως το 1.000.000 
# για να εξετάσουμε την αλυσίδα τετραγώνων των ψηφίων τους.
for x in range(1, 1000001):
    suma = 0
    z = list(str(x))    
    
    # Υπολογίζουμε το αρχικό άθροισμα των τετραγώνων των ψηφίων του τρέχοντος αριθμού x.
    for n in z:
        suma = suma + int(n)**2
    
    # Ο βρόχος while συνεχίζει επαναληπτικά να αθροίζει τα τετράγωνα των ψηφίων 
    # μέχρι το αποτέλεσμα να φτάσει είτε στο 89 είτε στο 1 (που είναι οι δύο τελικοί "ελκυστές").
    while suma != 89 and suma != 1:
        y = list(str(suma))
        suma = 0
        for i in y:
            suma = suma + int(i)**2
    else:
        # Μόλις ο βρόχος τερματίσει (δηλαδή βρούμε 89 ή 1), 
        # κατηγοριοποιούμε τον αρχικό αριθμό x στη αντίστοιχη λίστα.
        if suma == 89:
            s.append(x)  # Αριθμοί που καταλήγουν στο 89
        else:
            if suma == 1:
                t.append(x)  # Αριθμοί που καταλήγουν στο 1

# Εκτυπώνουμε το πλήθος των αριθμών που κατέληξαν στο 89 (λίστα s) 
# και αυτών που κατέληξαν στο 1 (λίστα t).
print(len(s), len(t))
        
    
       
               
                
                
            
        
    
               
            
    

        
    
    
   
            
                                  

            
            
            

                
                


           
                
                
    
        
        
    
    
