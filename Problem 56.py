# Project Euler - Problem 56: Powerful digit sum
# Υπολογισμός του αθροίσματος των ψηφίων για όλους τους αριθμούς a^b (όπου a, b από 1 έως 99) 
# και εύρεση της μέγιστης τιμής.

s = []
suma = 0

# Διπλός βρόχος για τη σάρωση όλων των πιθανών τιμών του a και του b από 1 έως 99
for a in range(1, 100):
    for b in range(1, 100):
        # Υπολογισμός της δύναμης a**b, μετατροπή σε συμβολοσειρά (string) 
        # και στη συνέχεια σε λίστα χαρακτήρων (ψηφίων)
        x = list(str(a**b))
        
        # Άθροισμα των επιμέρους ψηφίων του αριθμού
        for i in x:
            suma = suma + int(i)
            
        # Προσθήκη του συνολικού αθροίσματος ψηφίων στη λίστα s
        s.append(suma)
        # Μηδενισμός του αθροιστικού μετρητή για τον επόμενο αριθμό
        suma = 0

# Ταξινόμηση της λίστας με τα αθροίσματα ψηφίων σε αύξουσα σειρά
s.sort()

# Εκτύπωση του τελευταίου (μέγιστου) στοιχείου της ταξινομημένης λίστας
print(s[-1])




    
    

   
    
    

    
        
