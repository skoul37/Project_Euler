# Project Euler - Problem 7: 10001st prime
# Βρες τον 10001ο πρώτο αριθμό.

# Αρχικοποίηση του μετρητή πρώτων αριθμών (ξεκινάμε από το 2, καθώς έχουμε ήδη υπόψη το 2)
n = 2

# Ο πρώτος περιττός υποψήφιος αριθμός προς έλεγχο
x = 3

# Επανάληψη μέχρι να βρούμε τον 10000ο περιττό πρώτο (συνολικά τον 10001ο πρώτο)
while n < 10001:
    # Προχωράμε στον επόμενο περιττό αριθμό
    x = x + 2
    # Υποθέτουμε αρχικά ότι ο αριθμός είναι πρώτος
    isprime = True
    
    # Έλεγχος διαιρετότητας με περιττούς αριθμούς από το 3 μέχρι την τετραγωνική ρίζα του x
    for y in range(3, int(x**0.5) + 1, 2):
        if x % y == 0:
            isprime = False
            break  # Διακοπή μόλις βρεθεί διαιρέτης
            
    # Αν ο αριθμός είναι πρώτος, αυξάνουμε τον μετρητή n κατά 1
    if isprime:
        n = n + 1        

# Εκτύπωση του 10001ου πρώτου αριθμού (x) και του μετρητή (n)
print(x, n)
        
    
            
         

    
