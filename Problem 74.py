import time

# Εισάγουμε τη βιβλιοθήκη time για να μετρήσουμε πόσο χρόνο 
# κάνει ο αλγόριθμος να ολοκληρώσει τους υπολογισμούς.

def paragodiko (n):
    """
    Αυτή η συνάρτηση υπολογίζει αναδρομικά το παραγοντικό ενός 
    αριθμού (π.χ. 5! = 5 * 4 * 3 * 2 * 1 = 120).
    """
    if n == 0:
        return 1
    else:
        return n * paragodiko(n - 1)

def digit_chains (n):
    """
    Αυτή η συνάρτηση παίρνει έναν αριθμό n, σπάει τα ψηφία του,
    βρίσκει το παραγοντικό του καθενός μέσω της παραπάνω συνάρτησης,
    και επιστρέφει το συνολικό άθροισμά τους.
    """
    suma = 0
    for i in str(n):
        suma = suma + paragodiko(int(i))
    return suma

# Ξεκινάμε τη μέτρηση του χρόνου εκτέλεσης
t = time.time()
s = []
counter = 0

# Σαρώνουμε όλους τους αριθμούς από το 3 έως κάτω από το 1.000.000
for p in range(3, 1000000):
    # Ξεκινάμε μια νέα λίστα 's' για την τρέχουσα αλυσίδα, 
    # βάζοντας πρώτα τον αρχικό αριθμό p και μετά τον πρώτο υπολογισμό του
    s = s + [p]
    s.append(digit_chains(p))
    
    # Ο βρόχος while συνεχίζει να παράγει νέους αριθμούς στην αλυσίδα,
    # προσθέτοντας κάθε νέο όρο στη λίστα, εφόσον αυτός δεν έχει ήδη εμφανιστεί.
    while digit_chains(s[-1]) not in s:
        s.append(digit_chains(s[-1]))
        
        # Αν η αλυσίδα φτάσει ακριβώς τους 60 όρους, ελέγχουμε 
        # αν ο επόμενος όρος κλείνει σωστά τον κύκλο (υπάρχει ήδη στη λίστα).
        if len(s) == 60:
            if digit_chains(s[-1]) in s:
                counter = counter + 1  # Βρήκαμε μια έγκυρη αλυσίδα μήκους 60!
                s = []
                break
            else:
                s = []
                break
    else:
        # Αν η αλυσίδα τερματίσει (βρει ήδη υπάρχοντα αριθμό) 
        # πριν φτάσει το μέγεθος των 60 όρων, την απορρίπτουμε και μηδενίζουμε τη λίστα.
        s = []

# Εκτυπώνουμε το τελικό πλήθος των αλυσίδων και τον χρόνο που χρειάστηκε ο υπολογισμός
print(counter)
print(time.time() - t)

        







        
    
