# Project Euler - Problem 40: Champernowne's constant
# Υπολογισμός του γινομένου συγκεκριμένων ψηφίων (στις θέσεις 10^0 έως 10^6) 
# από τη δεκαδική σταθερά του Champernowne που παράγεται με τη συνένωση διαδοχικών ακεραίων.

# Αρχικοποίηση του string s ξεκινώντας με το "0.1" (όπου το πρώτο ψηφίο μετά την υποδιάστολη είναι στη θέση 1)
s = '0.1'

# Βήμα 1: Δημιουργία της ακολουθίας προσθέτοντας διαδοχικά τους ακέραιους από το 2 έως το 999.999
for i in range(2, 1000000):
    s = s + str(i)

# Βήμα 2: Εξαγωγή των ψηφίων στις επιθυμητές θέσεις (δείκτες) και πολλαπλασιασμός τους
# (Σημείωση: s[2] αντιστοιχεί στη θέση 1, s[11] στη θέση 10, s[101] στη θέση 100, κοκ.)
suma = int(s[2]) * int(s[11]) * int(s[101]) * int(s[1001]) * int(s[10001]) * int(s[100001]) * int(s[1000001])

# Εκτύπωση του τελικού γινομένου
print(suma)

    
