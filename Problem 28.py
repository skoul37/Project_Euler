# Project Euler - Problem 28: Number spiral diagonals
# Βρες το άθροισμα των αριθμών στις διαγωνίους ενός σπειροειδούς πίνακα 1001x1001.

suma, n = 0, 1

# Υπολογισμός των γωνιών/διαγωνίων της σπείρας για περιττές διαστάσεις x από 3 έως 1001
for x in range(3, 1002, 2):    
    suma = suma + x**2 + (x**2 - 2 * n)
    n = n + 1

# Εκτύπωση του συνολικού αθροίσματος των διαγωνίων (προσαρμοσμένο με βάση τη λογική του κώδικά σου)
print(suma + suma - 1002000 + 1)
