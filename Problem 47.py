# Project Euler - Problem 47: Distinct primes factors
# Εύρεση των πρώτων τεσσάρων διαδοχικών ακεραίων που έχουν από 4 διακριτούς πρώτους παράγοντες ο καθένας.

# Συνάρτηση ελέγχου πρώτου αριθμού και αποθήκευσης στη λίστα s
def isprime (n):
    isprime = True
    for a in range(3, int(n**0.5) + 1, 2):
        if n % a == 0:
            isprime = False
            break
    if isprime:
        s.append(n)
    return s

# Αρχική λίστα με τους πρώτους μικρούς πρώτους αριθμούς
s = [2, 3, 5, 7]

# Παραγωγή επιπλέον πρώτων αριθμών έως το 1000 για τους ελέγχους διαιρετότητας
for n in range(9, 1000, 2):
    isprime(n)

# Σάρωση διαδοχικών ακεραίων i, i+1, i+2, i+3
for i in range(100000, 999999):
    l1 = []  # Πρώτοι παράγοντες του i
    l2 = []  # Πρώτοι παράγοντες του i+1
    l3 = []  # Πρώτοι παράγοντες του i+2
    l4 = []  # Πρώτοι παράγοντες του i+3
    
    # Έλεγχος διαιρετότητας με τους αποθηκευμένους πρώτους αριθμούς για τους 4 διαδοχικούς αριθμούς
    for p in s:
        if i % p == 0:
            l1.append(p)
        if (i + 1) % p == 0:
            l2.append(p)
        if (i + 2) % p == 0:
            l3.append(p)
        if (i + 3) % p == 0:
            l4.append(p)
            
        # Αν και οι τέσσερις αριθμοί έχουν ακριβώς 4 διακριτούς πρώτους παράγοντες
        if len(l1) == len(l2) == len(l3) == len(l4) == 4:
            print(i, i + 1, i + 2, i + 3)
            exit()
           
    
        
