def amicable(n):
    """
    Αυτή η συνάρτηση υπολογίζει το άθροισμα των σusτωτών (γνησίων) διαιρετών 
    ενός αριθμού n. Ξεκινάει με το 1 (που είναι διαιρέτης για όλους), ελέγχει 
    αν υπάρχει τετραγωνική ρίζα ως ακέραιος διαιρέτης, και στη συνέχεια 
    σαρώνει ζευγάρια διαιρετών μέχρι την τετραγωνική ρίζα, προσθέτοντας 
    τόσο τον διαιρέτη i όσο και το αντίστοιχο πηλίκο n/i.
    """
    suma = 1
    if n % int(n**0.5) == 0:
        suma = suma + int(n**0.5)
    for i in range(2, int(n**0.5)):
        if n % i == 0:
            suma = suma + i + n / i
    return suma

new_counter = 0

# Σαρώνουμε όλους τους υποψήφιους αρχικούς αριθμούς από το 2 έως το 20.000
for i in range(2, 20000):
    counter = 1
    s = [i]
    
    # Ο βρόχος while χτίζει την αλυσίδα των αθροισμάτων διαιρετών. 
    # Συνεχίζει όσο ο επόμενος όρος δεν έχει ήδη εμφανιστεί στη λίστα 
    # και παραμένει κάτω από το όριο του 1.000.000.
    while amicable(s[-1]) not in s and amicable(s[-1]) < 1000000:
        s.append(amicable(s[-1]))
        counter = counter + 1
    else:
        # Μόλις ο βρόχος τερματίσει, ελέγχουμε αν κλείνει ο κύκλος 
        # (δηλαδή αν το επόμενο άθροισμα επιστρέφει ακριβώς στον αρχικό αριθμό s[0]).
        if amicable(s[-1]) == s[0]:
            # Αν βρούμε αλυσίδα με μεγαλύτερο ή ίσο μήκος από την προηγούμενη μέγιστη,
            # ενημερώνουμε το μέγιστο μετρητή και αποθηκεύουμε ολόκληρη τη λίστα s.
            if new_counter <= counter:
                new_counter = counter
                l = s

# Εκτυπώνουμε τη λίστα της μεγαλύτερης αλυσίδας που βρέθηκε
