# Project Euler - Problem 48: Self powers
# Υπολογισμός του αθροίσματος των αυτοδύναμων δυνάμεων από 1^1 έως 1000^1000 
# και εξαγωγή των τελευταίων δέκα ψηφίων του αποτελέσματος.

suma = 0

# Σάρωση των αριθμών από το 1 έως το 1000
for i in range(1, 1001):
    # Προσθήκη της δύναμης i^i στο συνολικό άθροισμα
    suma = suma + i**i

# Μετατροπή του συνολικού αθροίσματος σε συμβολοσειρά (string) 
# και απομόνωση των τελευταίων 10 χαρακτήρων (ψηφίων) με χρήση slicing [-10:]
print(str(suma)[-10:])
