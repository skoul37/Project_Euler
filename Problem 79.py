s = [319,680,180,690,129,620,762,689,762,318,368,710,720,710,629,168,160,689,716,731,736,729,316,729,729,710,769,290,719,680,318,389,162,289,162,718,729,319,790,680,890,362,319,760,316,729,380,319,728,716]
l = []

# Ο παρακάτω βρόχος διατρέχει κάθε αριθμό της λίστας s.
# Στη συνέχεια, μετατρέπει τον αριθμό σε string για να εξετάσει ξεχωριστά κάθε ψηφίο του.
# Αν το ψηφίο (μετατραπέν ξανά σε ακέραιο) δεν υπάρχει ήδη στη λίστα l,
# το προσθέτει εκεί, συλλέγοντας έτσι όλα τα μοναδικά ψηφία που εμφανίζονται στα δεδομένα.
for i in s:
    for r in str(i):
        if int(r) not in l:
            l.append(int(r))

# Εκτυπώνει το συνολικό πλήθος των στοιχείων της αρχικής λίστας 
# και τη λίστα με τα μοναδικά ψηφία που εντοπίστηκαν.
print(len(s), l)
