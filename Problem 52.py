# Project Euler - Problem 52: Permuted multiples
# Εύρεση του μικρότερου θετικού ακεραίου x του οποίου τα πολλαπλάσια 
# 2x, 3x, 4x, 5x και 6x αποτελούνται από τα ακριβώς ίδια ψηφία (αναγραμματισμούς).

def pandigital (i):
    # Μετατροπή του αριθμού σε λίστα χαρακτήρων (ψηφίων)
    x = list(str(i))
    # Ταξινόμηση των ψηφίων σε αύξουσα σειρά ώστε να συγκρίνονται εύκολα
    x.sort()
    b = ''
    # Ένωση των ταξινομημένων ψηφίων πίσω σε συμβολοσειρά (string)
    pandigital = b.join(x)
    return pandigital

# Σάρωση των αριθμών στο κατάλληλο διάστημα (ξεκινώντας από 100000)
for i in range(100000, 199999):
    # Έλεγχος αν ταξινομημένα τα ψηφία του i και των πολλαπλασίων του (2i έως 6i) είναι πανομοιότυπα
    if (pandigital(i)) == (pandigital(2 * i)) == (pandigital(3 * i)) == (pandigital(4 * i)) == (pandigital(5 * i)) == (pandigital(6 * i)):
        # Εκτύπωση του ζητούμενου αριθμού
        print(i)
