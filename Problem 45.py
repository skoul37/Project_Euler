# Project Euler - Problem 45: Triangular, pentagonal, and hexagonal
# Εύρεση του επόμενου αριθμού που είναι ταυτόχρονα τριγωνικός, πενταγωνικός και εξαγωνικός 
# (Σημείωση: Κάθε εξαγωνικός αριθμός είναι εξ ορισμού και τριγωνικός αριθμός, 
# οπότε αρκεί η σύγκριση μεταξύ τριγωνικών/εξαγωνικών και πενταγωνικών αριθμών).

s = []  # Λίστα για την αποθήκευση των αριθμών (τριγωνικών/εξαγωνικών)
z = []  # Λίστα για την αποθήκευση των πενταγωνικών αριθμών
p = 0
h = 0

# Βήμα 1: Δημιουργία σειράς αριθμών με βήμα 3 (που αντιστοιχούν σε εξαγωνικούς/τριγωνικούς αριθμούς)
for x in range(1, 150000, 3):
    p = p + x
    s.append(p)

# Βήμα 2: Δημιουργία σειράς πενταγωνικών αριθμών με βήμα 4
for i in range(1, 150000, 4):
    h = h + i
    z.append(h)

# Βήμα 3: Σύγκριση των δύο λιστών για την εύρεση κοινών στοιχείων
for t in s:
    for n in z:
        if t == n:
            print(t)  # Εκτύπωση των κοινών αριθμών (συμπεριλαμβανομένου του 40755 και του επόμενου)
   
   
   
   




  

  
         

         


   

