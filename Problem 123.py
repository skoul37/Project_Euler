def protos(n):
    """
    Αυτή η συνάρτηση ελέγχει αν ένας περιττός αριθμός n είναι πρώτος. 
    Ξεκινάει θεωρώντας τον πρώτο (isprime=True) και τον δοκιμάζει διαιρώντας τον 
    με όλους τους περιττούς αριθμούς από το 3 μέχρι την τετραγωνική του ρίζα (int(n**0.5) + 1). 
    Αν βρεθεί έστω και ένας ακριβής διαιρέτης, ο αριθμός δεν είναι πρώτος, 
    οπότε διακόπτεται ο βρόχος (break). Αν παραμείνει πρώτος, επιστρέφει 1.
    """
    isprime = True
    for y in range(3, int(n**0.5) + 1, 2):
        if n % y == 0:
            isprime = False
            break
    if isprime:
        return 1

def remainder (a, n):
    """
    Αυτή η συνάρτηση υπολογίζει το υπόλοιπο της διαίρεσης της αλγεβρικής παράστασης 
    (a-1)^n + (a+1)^n με το τετράγωνο του αριθμού a (δηλαδή a^2), 
    αξιοποιώντας τον ίδιο μαθηματικό υπολογισμό modulo που είδαμε και στο προηγούμενο πρόβλημα.
    """
    c = (a - 1)**n + (a + 1)**n
    r = c - ((c // a**2) * a**2)
    return r

# Αρχικοποιούμε τους μετρητές: ο counter ξεκινά από το 4 και ο x από το 9, 
# συνδέοντας τους διαδοχικούς περιττούς πρώτους αριθμούς με τη αύξουσα τιμή του εκθέτη/μετρητή.
counter = 4
x = 9

# Κεντρικός βρόχος αναζήτησης:
# Σαρώνει αενάως (while True) όλους τους περιττούς αριθμούς ξεκινώντας από το 9.
while True:
    x = x + 2
    
    # Αν ο τρέχων αριθμός x είναι πρώτος...
    if protos(x) == 1:
        counter = counter + 1  # Αυξάνουμε τον μετρητή κατά 1
        
        # Υπολογίζουμε το υπόλοιπο για τον πρώτο a = x και εκθέτη n = counter. 
        # Αν αυτό ξεπεράσει το όριο των 10^10, εκτυπώνουμε τον μετρητή και τον αριθμό x, 
        # τερματίζοντας οριστικά το πρόγραμμα.
        if remainder(x, counter) > 10**10:
            print(counter, x)
            exit()

    
    
 

