# Project Euler - Problem 36: Double-base palindromes
# Υπολογισμός του αθροίσματος όλων των αριθμών κάτω από το 1.000.000 
# που είναι παλίνδρομοι τόσο στη δεκαδική (base 10) όσο και στη δυαδική (base 2) αναπαράστασή τους.

# Αρχικοποίηση λίστας t για την αποθήκευση των δεκαδικών παлиндρομικών αριθμών
t = []

# Βήμα 1: Εύρεση όλων των παλίνδρομων αριθμών από το 1 έως το 1.000.000 στη δεκαδική βάση
for k in range(1, 1000001):
    # Έλεγχος αν ο αριθμός (ως string) ισούται με την αντίστροφη μορφή του (str(k)[::-1])
    if str(k) == str(k)[::-1]:
        t = t + [k]  # Προσθήκη του δεκαδικού παλίνδρομου στη λίστα t

# Αρχικοποίηση λίστας s για τους αριθμούς που είναι παλίνδρομοι και στις δύο βάσεις
s = []

# Βήμα 2: Έλεγχος των δεκαδικών παλίνδρομων για το αν είναι παλίνδρομοι και στο δυαδικό σύστημα
for n in t:
    # Μετατροπή του αριθμού n σε δυαδική μορφή (με το πρόθεμα '0b') 
    # [Σημείωση: το προστιθέμενο string "+b0" στο δικό σου κώδικα προστίθεται απλώς στο τέλος ως παράδειγμα/δοκιμή, 
    #  ενώ για το δυαδικό συνήθως αφαιρούμε το πρόθεμα '0b' με bin(n)[2:]]
    x = bin(n) + "b0"
    
    # Έλεγχος αν η δυαδική αναπαράσταση είναι παλινδρομική
    if str(x) == str(x)[::-1]:
        s.append(n)  # Αν είναι και στις δύο βάσεις, τον προσθέτουμε στη λίστα s

# Εκτύπωση της λίστας με τους διπλά παλίνδρομους αριθμούς
print(s)

# Αρχικοποίηση μεταβλητής για τον υπολογισμό του συνολικού αθροίσματος
sum = 0
for i in s:
    sum = sum + int(i)

# Εκτύπωση του τελικού αθροίσματος
print(sum)
    
    
    
   

        
        




    


