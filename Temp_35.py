# Συνάρτηση υπολογισμού της ακολουθίας Fibonacci μέχρι να βρεθεί ο πρώτος 1000-ψήφιος αριθμός
def fibo():
    s = [1, 1, 2, 3]
    x = 0
    # Επανάληψη όσο το μήκος του τελευταίου αριθμού της ακολουθίας είναι μικρότερο από 1000 ψηφία
    while len(str(s[-1])) < 1000:
        x = s[-1] + s[-2]
        s.append(x)
        x = 0
    else:
        # Εκτύπωση του συνολικού πλήθους των όρων (δείκτης του πρώτου 1000-ψήφιου αριθμού)
        print(len(s))

