# Project Euler - Problem 35: Circular primes
# Υπολογισμός του πλήθους των κυκλικών πρώτων αριθμών κάτω από το 1.000.000.
# (Ένας πρώτος θεωρείται κυκλικός αν όλες οι κυκλικές μεταθέσεις των ψηφίων του είναι επίσης πρώτοι).

s = []  # Λιστα για την αποθήκευση όλων των πρώτων αριθμών μέχρι το 1.000.000
l = []  # Λίστα για την καταγραφή των πρώτων που ΔΕΝ είναι κυκλικοί (ή παρουσιάζουν σύνθετες κυκλικές μεταθέσεις)

# Βήμα 1: Εύρεση όλων των περιττών πρώτων αριθμών από το 13 έως το 1.000.000
for x in range(13, 1000001, 2):
    isprime = True
    # Έλεγχος διαιρετότητας μέχρι την τετραγωνική ρίζα του x
    for y in range(3, int(x**0.5) + 1, 2):
        if x % y == 0:
            isprime = False
            break        
    # Αν είναι πρώτος, τον προσθέτουμε στη λίστα s
    if isprime:
        s.append(x)

# Βήμα 2: Έλεγχος για το αν οι κυκλικές μεταθέσεις κάθε πρώτου είναι επίσης πρώτοι αριθμοί
for i in s[:]:
    n = 0
    z = str(i)
    
    # Μετατόπιση των ψηφίων κυκλικά μέχρι να ελεγχθούν όλες οι πιθανές θέσεις
    while n < len(z) - 1:
        # Κυκλική μετατόπιση: το τελευταίο ψηφίο γίνεται πρώτο (π.χ. '197' -> '719')
        z = z[-1] + z[0:-1]
        k = int(z)
        isprime = True
        
        # Έλεγχος αν η νέα κυκλική μετάθεση (k) είναι πρώτος αριθμός
        for t in range(2, int(k**0.5) + 1):
            if k % t == 0:
                isprime = False
                l.append(i)  # Αν βρεθεί διαιρέτης, ο αριθμός δεν είναι κυκλικός πρώτος
                n = n + len(z) - 1  # Τερματισμός ελέγχου για τον τρέχοντα αριθμό
                break
                
        # Αν η μετάθεση είναι επίσης πρώτη, προχωράμε στο επόμενο ψηφίο/μετατόπιση
        if isprime:
            n = n + 1

# Εκτύπωση του τελικού πλήθους (υπολογίζοντας βάσει της διαφοράς των λιστών και διορθωτικών παραγόντων)
print(len(s) - len(l) + 5)




        
        



    

    
