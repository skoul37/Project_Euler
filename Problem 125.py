def palidromo (n):
    """
    Αυτή η συνάρτηση ελέγχει αν ένας αριθμός n είναι παλινδρομικός 
    (δηλαδή αν διαβάζεται ακριβώς το ίδιο και από την αρχή και από το τέλος, 
    όπως το 121 ή το 484). Μετατρέπει τον αριθμό σε string και συγκρίνει 
    την τυπική του μορφή με την αντίστροφή της ([::-1]). 
    Αν είναι παλινδρομικός, επιστρέφει τον αριθμό· αλλιώς επιστρέφει None.
    """
    if str(n) == str(n)[::-1]:
        return n

# Προ-υπολογισμός τετραγώνων:
# Δημιουργούμε μια λίστα l με τα τετράγωνα όλων των ακεραίων από το 1 έως το 7.071 
# (καθώς 7.071^2 ≈ 50.000.000, καλύπτοντας το απαιτούμενο εύρος).
l = [i**2 for i in range(1, 7072)]
s = []

def elexos ():
    """
    Αυτή η συνάρτηση εκτελεί έναν συστηματικό έλεγχο ολισθαίνοντος παραθύρου 
    (sliding window / running sum) πάνω στη λίστα των τετραγωνικών αριθμών. 
    Αθροίζει διαδοχικά τετράγωνα ξεκινώντας από το πρώτο στοιχείο της λίστας l. 
    Αν το τρέχον άθροισμα (suma) είναι μικρότερο από 100.000.000 και ταυτόχρονα 
    παλινδρομικό, το αποθηκεύει στη λίστα s. Αν το άθροισμα ξεπεράσει το όριο, 
    αφαιρεί το πρώτο στοιχείο της λίστας (l.remove(l[0])) για να ξεκινήσει 
    την επόμενη σάρωση από το επόμενο τετράγωνο.
    """
    i = 0
    suma = l[0]
    while suma < 100000000 and i < len(l):
        i = i + 1
        if i < len(l):
            suma = suma + l[i]
            if suma < 100000000:
                if palidromo(suma) == suma:
                    s.append(suma)
            else:
                l.remove(l[0])

# Επαναληπτική εκτέλεση:
# Καλούμε τη συνάρτηση elexos τόσες φορές όσες και τα στοιχεία της λίστας, 
# εξασφαλίζοντας ότι θα ελεγχθούν όλες οι πιθανές διαδοχικές αθροιστικές ακολουθίες.
for i in range(1, 7072):
    elexos()

# Ταξινομούμε τη λίστα των παλινδρομικών αθροισμάτων
s.sort()
k = []
telos = 0

# Εντοπισμός διπλότυπων:
# Ο παρακάτω βρόχος σαρώνει τη ταξινομημένη λίστα s για να εντοπίσει τυχόν 
# ίδιους παλινδρομικούς αριθμούς που προέκυψαν από διαφορετικές διαδρομές αθροίσματος, 
# αποθηκεύοντάς τους στη λίστα k.
for n in range(0, len(s) - 1):
    if s[n] == s[n + 1]:
        k.append(s[n])

# Υπολογισμός τελικού αθροίσματος:
# Προσθέτουμε αρχικά όλα τα στοιχεία της λίστας s στη μεταβλητή telos...
for n in s:
    telos = telos + n

# ...και στη συνέχεια αφαιρούμε τα διπλότυπα στοιχεία (της λίστας k) 
# ώστε κάθε μοναδικός παλινδρομικός αριθμός να μετρηθεί ακριβώς μία φορά.
for n in k:
    telos = telos - n

# Εκτυπώνουμε το τελικό άθροισμα
print(telos)

    
        
    
        
        
   


        
        
