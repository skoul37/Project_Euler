# Project Euler - Problem 12: Highly divisible triangular number
# Βρες τον πρώτο τριγωνικό αριθμό που έχει πάνω από 500 διαιρέτες.

# Συνάρτηση που υπολογίζει τον x-οστό τριγωνικό αριθμό
def triangle(x):
    y = x * (x + 1) / 2
    return y

x = 1
s = []

# Επανάληψη μέχρι ο τριγωνικός αριθμός να αποκτήσει περισσότερους από 500 διαιρέτες
while len(s) <= 500:
    s = []
    x = x + 1
    i = 1
    # Εύρεση όλων των διαιρετών του τρέχοντος τριγωνικού αριθμού
    while i * i <= triangle(x):
        if triangle(x) % i == 0:
            s.append(i)
            # Αν ο διαιρέτης δεν είναι το τετραγωνικό ρίζα, προσθέτουμε και το συμμετρικό του
            if triangle(x) / i != i:
                s.append(triangle(x) / i)
        i = i + 1

# Εκτύπωση του τριγωνικού αριθμού και του πλήθους των διαιρετών του
print(triangle(x), len(s))



