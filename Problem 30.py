# Project Euler - Problem 30: Digit fifth powers
# Βρες το άθροισμα όλων των αριθμών που μπορούν να γραφτούν ως το άθροισμα των πέμπτων δυνάμεων των ψηφίων τους.

c = 0

# Έλεγχος όλων των αριθμών από το 2 μέχρι το 1.000.000 (το άνω όριο για το πρόβλημα αυτό)
for i in range(2, 1000000):
    suma = 0
    x = str(i)
    y = list(x)
    
    # Υπολογισμός του αθροίσματος των πέμπτων δυνάμεων των ψηφίων του αριθμού
    for n in y:
        suma = suma + int(n)**5
        
    # Αν το άθροισμα ισούται με τον ίδιο τον αριθμό, τον προσθέτουμε στο συνολικό άθροισμα c
    if suma == i:        
        c = c + i

# Εκτύπωση του τελικού αθροίσματος
print(c) 
          
        
        
            
            
        
    

