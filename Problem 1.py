# Project Euler - Problem 1: Multiples of 3 or 5
# Βρες το άθροισμα όλων των φυσικών αριθμών κάτω από το 1000 που είναι πολλαπλάσια του 3 ή του 5.

# Υπολογισμός και εκτύπωση του αθροισματος όλων των αριθμών i από το 1 έως το 999 
# εφόσον το i διαιρείται με το 3 ή με το 5 (το υπόλοιπο % είναι 0)
print(sum(i for i in range(1, 1000) if i % 3 == 0 or i % 5 == 0))
