from math import sqrt
from decimal import * 

# Ρυθμίζουμε την ακρίβεια της βιβλιοθήκης Decimal στα 105 ψηφία, 
# ώστε να έχουμε αρκετά δεκαδικά ψηφία για τους υπολογισμούς μας.
getcontext().prec = 105

s = []
suma = 0
totalsuma = 0

# Πρώτος βρόχος: Υπολογίζουμε την τετραγωνική ρίζα για όλους τους 
# ακέραιους αριθμούς από το 1 έως το 99, αποθηκεύοντάς τους ως αντικείμενα Decimal.
for i in range(1, 100):
    s = s + [(Decimal(i).sqrt())]

# Φιλτράρισμα: Αφαιρούμε από τη λίστα τους αριθμούς που είναι ρητοί 
# (δηλαδή οι τέλειες ρίζες, π.χ. √4 = 2.0), των οποίων το string είναι μικρότερο από 101 χαρακτήρες.
for i in s:
    if len(str(i)) < 101:
        s.remove(i)

# Άθροισμα δεκαδικών ψηφίων: Για κάθε άρρητη ρίζα που απέμεινε στη λίστα, 
# διατρέχουμε τα πρώτα 100 δεκαδικά ψηφία της (αποκλείοντας την υποδιαστολή) και τα προσθέτουμε στο άθροισμα.
for i in s:
    suma = 0
    for r in str(i)[2:101]:
        suma = suma + int(r)
    totalsuma = totalsuma + suma

# Προσθήκη ακέραιου μέρους: Σε αυτό το βήμα, προσθέτουμε στο συνολικό άθροισμα 
# και το πρώτο ψηφίο κάθε αριθμού (δηλαδή το ακέραιο μέρος, πριν την υποδιαστολή).
for r in s:
    totalsuma = totalsuma + int(str(r)[0])

# Εκτυπώνουμε το τελικό, συνολικό άθροισμα όλων των ψηφίων
print(totalsuma)









