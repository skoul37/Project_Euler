from fractions import Fraction

def frac(n):
    """
    Αυτή η συνάρτηση χρησιμοποιεί μια σταθερή βάση αναφοράς με παρονομαστή 999.999 
    (το οποίο είναι πολλαπλάσιο του 7: 7 * 142.857 = 999.999, άρα συνδέεται απευθείας 
    με το κλάσμα 3/7 που ισοδυναμεί με το 428.571 / 999.999).
    
    Ελέγχει αν το n / 999.999:
    1. Δεν διαιρείται τέλεια από το n (999999 % n != 0), αποφεύγοντας περιττές απλοποιήσεις.
    2. Είναι αυστηρά μικρότερο από το όριο 3/7.
    """
    if 999999 % n != 0 and Fraction(n, 999999) < Fraction(3, 7):
        return Fraction(n, 999999)
    else:
        return 0

newfrac = 0

# Σαρώνουμε τους αριθμούς για να βρούμε το μέγιστο κλάσμα 
# με αυτόν τον παρονομαστή που πλησιάζει ασφυκτικά το 3/7 από τα αριστερά.
for n in range(2, 500000):
    if newfrac <= frac(n):
        newfrac = frac(n)

# Ο κώδικας θα τυπώσει: 428570/999999
print(newfrac)

