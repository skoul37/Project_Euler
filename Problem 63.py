# Project Euler - Problem 63: Powerful digit counts
# Υπολογισμός του πλήθους των θετικών ακεραίων n-οστών δυνάμεων 
# που έχουν ακριβώς n ψηφία (δηλαδή len(i**r) == r).

counter = 0

# Σάρωση των πιθανών βάσεων i από 1 έως 9 
# (καθώς για i >= 10, η δύναμη 10^r θα έχει πάντα περισσότερα από r ψηφία)
for i in range(1, 10):
    # Σάρωση των εκθετών r από 1 έως 999
    for r in range(1, 1000):
        # Έλεγχος αν το πλήθος των ψηφίων του i^r είναι ακριβώς ίσο με τον εκθέτη r
        if len(str(i**r)) == r:
            counter = counter + 1

# Εκτύπωση του συνολικού πλήθους των τέτοιων δυνάμεων
print(counter)
