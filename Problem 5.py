# Project Euler - Problem 5: Smallest multiple
# Βρες τον μικρότερο θετικό αριθμό που διαιρείται ακριβώς από όλους τους αριθμούς από το 1 έως το 20.

# Επανάληψη σε ένα εύρος τιμών για τον έλεγχο υποψηφίων αριθμών
for r in range(100000000, 1000000000):
    # Έλεγχος αν ο αριθμός r διαιρείται ταυτόχρονα με όλους τους αριθμούς από το 11 έως το 20
    # (αν διαιρείται με αυτούς, καλύπτονται αυτόματα και οι μικρότεροι από 1 έως 10)
    if (
        r % 11 == 0
        and r % 12 == 0
        and r % 13 == 0
        and r % 14 == 0
        and r % 15 == 0
        and r % 16 == 0
        and r % 17 == 0
        and r % 18 == 0
        and r % 19 == 0
        and r % 20 == 0
    ):
        # Εκτύπωση του πρώτου (μικρότερου) αριθμού που ικανοποιεί τη συνθήκη
        print(r)
        # Τερματισμός του προγράμματος αμέσως μόλις βρεθεί η λύση
        exit()



    
