def remainder (a):
    """
    Αυτή η συνάρτηση υπολογίζει το μέγιστο υπόλοιπο (R_max) που προκύπτει 
    όταν η παράσταση (a-1)^n + (a+1)^n διαιρείται με το a^2, δοκιμάζοντας 
    διαδοχικές τιμές του εκθέτη n από 1 έως 1499.
    """
    new_r = 0
    for n in range(1, 1500):
        # Υπολογίζουμε την τιμή της έκφρασης για το τρέχον n
        c = (a - 1)**n + (a + 1)**n
        
        # Υπολογίζουμε το υπόλοιπο της διαίρεσης c με το a^2 (ισοδύναμο με c % a**2)
        r = c - ((c // a**2) * a**2)
        
        # Αν το νέο υπόλοιπο είναι μεγαλύτερο ή ίσο από το προηγούμενο μέγιστο, 
        # το ενημερώνουμε· αλλιώς διατηρούμε τη μέγιστη τιμή που είχαμε βρει.
        if new_r <= r:
            new_r = r
        else:
            new_r = new_r
    return new_r  

s = []
suma = 0

# Κεντρικός βρόχος: 
# Διατρέχουμε όλες τις τιμές του a από το 3 έως το 1000, 
# καλούμε τη συνάρτηση remainder για καθεμία από αυτές, 
# και αθροίζουμε τα μέγιστα υπολοιπόμενα αποτελέσματα στη μεταβλητή suma.
for a in range(3, 1001):
    suma = suma + remainder(a)

# Εκτυπώνουμε το τελικό συνολικό άθροισμα
print(suma)
