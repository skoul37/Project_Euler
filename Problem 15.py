# Project Euler - Problem 15: Lattice paths
# Βρες πόσες διαδρομές υπάρχουν από την πάνω-αριστερή γωνία σε ένα πλέγμα 20x20 έως την κάτω-δεξιά γωνία, κινούμενος μόνο δεξιά και κάτω.

# Συνάρτηση για τον υπολογισμό του παραγοντικού ενός αριθμού (n!)
def paragontiko (n):
    if n == 0:
        return 1
    else:
        return n * paragontiko(n - 1)

# Συνάρτηση για τον υπολογισμό των συνδυασμών (n ανά r), δηλαδή τον διωνυμικό συντελεστή C(n, r)
def Compinatoric (n, r):
    c = paragontiko(n) / (paragontiko(r) * paragontiko(n - r))
    return c

# Υπολογισμός και εκτύπωση των διαδρομών για ένα πλέγμα 20x20 (συνδυασμός 40 επιλογών συνολικά, 20 για κάθε κατεύθυνση)
print(Compinatoric(40, 20))
                      
