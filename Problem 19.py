# Project Euler - Problem 19: Counting Sundays
# Πόσες φορές έπεσε η πρώτη μέρα του μήνα σε Κυριακή κατά τον 20ό αιώνα (1 Ιανουαρίου 1901 έως 31 Δεκεμβρίου 2000);

# Συνάρτηση που ελέγχει αν ένα έτος είναι δίσεκτο (απλοποιημένος έλεγχος με το 4)
def disektos(n):
    if n % 4 == 0:
        return 1
    else:
        return 0
# Λίστα με τις ημέρες κάθε μήνα (για μη δίσεκτο έτος)
mines = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
meres = [1, 2, 3, 4, 5, 6, 7]
s = []
sunday = 0
l = 0

# Επανάληψη για όλα τα έτη από το 1901 έως το 2000
for i in range(1901, 2001):
    for j in mines:
        k = 0
        # Αν ο μήνας είναι ο Φεβρουάριος (28 μέρες), προσθέτουμε την επιπλέον μέρα αν είναι δίσεκτο
        if j == 28:
            j = j + disektos(i)
        # Μέτρησις ημερών του μήνα
        while k != j:
            k = k + 1
            if l != 7:
                l = l + 1
            else:
                l = 1
            # Έλεγχος αν η 1η του μήνα (k==1) είναι Κυριακή (l==6)
            if k == 1 and l == 6:
                sunday = sunday + 1
        else:
            k = 0

# Εκτύπωση του συνολικού πλήθους των Κυριακών που έπεσαν στην αρχή του μήνα
print(sunday)
                        
                
            
    
        
    

