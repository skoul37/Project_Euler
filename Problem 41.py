# Project Euler - Problem 41: Pandigital prime
# Εύρεση του μεγαλύτερου πανψηφιακού πρώτου αριθμού. 
# (Ο κώδικας ελέγχει αντίστροφα από το μέγιστο δυνατό 7ψήφιο πανψηφιακό 7654321, 
#  καθώς οι 8ψήφιοι και 9ψήφιοι πανψηφιακοί διαιρούνται πάντα με το 3 λόγω αθροίσματος ψηφίων).

# Συνάρτηση ελέγχου αν ένας αριθμός n είναι πρώτος
def isprime (n):
    n = n
    isprime = True
    # Έλεγχος διαιρετότητας με περιττούς αριθμούς από το 3 μέχρι την τετραγωνική ρίζα του n
    for i in range(3, int(n**0.5) + 1, 2):
        if n % i == 0:
            isprime = False
            break
    # Αν ο αριθμός είναι πρώτος, τον εκτυπώνουμε και τερματίζουμε αμέσως το πρόγραμμα
    if isprime:
        print(n)
        exit()

# Συνάρτηση ελέγχου αν ένας αριθμός είναι πανψηφιακός (1 έως len(n))
def pandigital (n):
    x = list(str(n))
    x.sort()
    a = '1234567'
    b = ''
    pandigital = b.join(x)
    
    # Έλεγχος αν τα ταξινομημένα ψηφία του αριθμού ταιριάζουν με το αντίστοιχo πλήθος ψηφίων (π.χ. '1234567')
    if pandigital == a[0:len(str(n))]:
        isprime(n)  # Αν είναι πανψηφιακός, καλούμε τη συνάρτηση ελέγχου πρώτου

# Σάρωση προς τα κάτω από το 7.654.321 μέχρι το 3 (μόνο στους περιττούς αριθμούς με βήμα -2)
for n in range(7654321, 3, -2):
    pandigital(n)
    
    
            
    
    

            
                    
        


    


